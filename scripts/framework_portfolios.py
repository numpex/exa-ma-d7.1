#!/usr/bin/env python3
"""Assemble standalone framework + application fiches without editing report sources."""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import tomllib
import zipfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

try:
    from .framework_previews import frameworks
    from .framework_publication import framework_id
    from .sync_applications import read_csv, tex
    from .framework_application_map import STAGES, application_label
    from .workpackage_previews import check_log, read_labels, run
except ImportError:
    from framework_previews import frameworks
    from framework_publication import framework_id
    from sync_applications import read_csv, tex
    from framework_application_map import STAGES, application_label
    from workpackage_previews import check_log, read_labels, run

ROOT = Path(__file__).resolve().parents[1]
LATEX_FLAGS = ['latexmk', '--shell-escape', '-pdf', '-halt-on-error',
               '-interaction=nonstopmode', '-synctex=1']
MARKER = '% Generated by scripts/framework_portfolios.py; edit catalogue/reconciliation inputs.\n'


def portfolios(root=ROOT):
    """Use Sheet associations; retain explicitly reconciled repository-only fiches."""
    catalogue = frameworks(root)
    _, framework_rows = read_csv(root / 'data/frameworks.csv')
    names = {row['Name'].strip().casefold(): framework_id(row['Name'])
             for row in framework_rows}
    _, apps = read_csv(root / 'data/applications.csv')
    _, reconciled = read_csv(root / 'data/application-reconciliation-v3.csv')
    _, benchmarks = read_csv(root / 'data/benchmark-registry-v3.csv')
    rec = {row['application_id']: row for row in reconciled}
    by_id = {row['id']: row for row in apps}
    if len(by_id) != len(apps) or len(rec) != len(reconciled):
        raise ValueError('Duplicate application IDs')
    evidence = {}
    for row in benchmarks:
        evidence.setdefault(row['application_id'], []).append(row['benchmark_status'])
    # A repository-only association is editorial and must never look like a Sheet row.
    for row in reconciled:
        if row['application_id'] not in by_id:
            if row['status_maturity'] != 'repository-only':
                raise ValueError(f"Unreconciled application absent from Sheet: {row['application_id']}")
            by_id[row['application_id']] = {
                'id': row['application_id'], 'name': row['application_id'],
                'Framework': row['software_framework'], 'work_package': row['wp_mapping'],
                'status': 'repository-only', 'application_type': row['application_type']}
    result = {key: [] for key in catalogue}
    for app_id, app in sorted(by_id.items()):
        if not re.fullmatch(r'app-[a-z0-9-]+', app_id):
            raise ValueError(f'Unsafe application ID: {app_id}')
        if app_id not in rec:
            raise ValueError(f'Reconcile the application fiche first: {app_id}')
        source = Path(rec[app_id]['latex_spec'])
        if source.is_absolute() or '..' in source.parts or not (root / source).is_file():
            raise ValueError(f'Invalid application source: {source}')
        grouped = source.as_posix() == 'chapters/applications/specs/app-proposed.tex'
        dedicated = source.parent.as_posix() == 'chapters/applications/specs' and not grouped
        if grouped:
            content = (root / source).read_text()
            if f'%<*{app_id}>' not in content or f'%</{app_id}>' not in content:
                raise ValueError(f'Missing shared-fiche selection markers: {app_id}')
        if not dedicated and not grouped and not (root / f'chapters/applications/metadata/{app_id}.tex').exists():
            raise ValueError(f'No dedicated fiche or catalogue metadata: {app_id}')
        item = dict(app, source=source.as_posix(),
                    spec=source.stem if dedicated else app_id,
                    grouped_source=source.as_posix() if grouped else '',
                    label=application_label(root, app, rec) if dedicated else f'app:fiche:{app_id}',
                    evidence='; '.join(dict.fromkeys(evidence.get(app_id, [])))
                             or 'No benchmark record')
        # Match complete catalogue names, never substrings or application-name guesses.
        associated = {names[value.strip().casefold()]
                      for value in re.split(r'[,;]', app['Framework'])
                      if value.strip().casefold() in names}
        for key in associated & result.keys():
            result[key].append(item)
    return result


def render_index(apps):
    if not apps:
        return MARKER + ('\\noindent No application association is recorded for this framework '
                         'in the current catalogue.\\par\\medskip\n')
    header = (r'\textbf{Application / type} & \textbf{WP(s)} & '
              r'\textbf{Catalogue stage} & \textbf{Benchmark status} \\')
    compact = len(apps) > 10
    lines = [MARKER, r'\section*{Framework and applications}',
             'This fiche combines the framework description and its associated application sections.',
             'Catalogue readiness and benchmark status are reported separately.',
             (r'\begingroup\footnotesize\setlength{\tabcolsep}{3pt}\renewcommand{\arraystretch}{1.05}'
              if compact else r'\begingroup\small\setlength{\tabcolsep}{3pt}\renewcommand{\arraystretch}{1.15}'),
             r'\begin{longtable}{@{}>{\raggedright\arraybackslash}p{0.40\linewidth}',
             r'>{\raggedright\arraybackslash}p{0.12\linewidth}',
             r'>{\raggedright\arraybackslash}p{0.21\linewidth}',
             r'>{\raggedright\arraybackslash}p{\dimexpr0.27\linewidth-6\tabcolsep\relax}@{}}',
             r'\toprule', header, r'\midrule\endfirsthead',
             r'\multicolumn{4}{@{}l}{\textit{Associated applications (continued)}}\\',
             r'\toprule', header, r'\midrule\endhead\bottomrule\endfoot']
    for app in apps:
        title = tex(app['name'])
        if app['name'] == app['id']:
            title = r'\nolinkurl{' + app['id'] + '}'
        wps = sorted(set(re.findall(r'WP([1-7])', app['work_package'])))
        wp_links = ', '.join(r'\hyperref[chap:wp' + wp + ']{WP' + wp + '}' for wp in wps) or '---'
        stage = STAGES.get(app['status'], app['status'].replace('-', ' ').capitalize())
        lines.append(r'\hyperref[' + app['label'] + ']{' + title + '}'
                     + r'\newline {\footnotesize ' + tex(app['application_type']) + '}'
                     + ' & ' + wp_links + ' & ' + tex(stage) + ' & ' + tex(app['evidence']) + r' \\')
        lines.append(r'\addlinespace[1pt]' if compact else r'\addlinespace[3pt]')
    lines += [r'\end{longtable}\endgroup', r'\clearpage']
    return '\n'.join(lines) + '\n'


def render_sections(apps):
    return MARKER + ''.join(
        r'\PortfolioApplication{' + app['id'] + '}{' + app['spec'] + '}{'
        + app['grouped_source'] + '}\n' for app in apps)


def sync(root=ROOT, write=False):
    abbreviations = (root / 'sections/abbreviations.tex').read_text()
    match = re.search(r'\\begin\{acronym\}(?:\[[^\]]*\])?(.*?)\\end\{acronym\}',
                      abbreviations, re.S)
    if not match:
        raise ValueError('No shared acronym definitions in sections/abbreviations.tex')
    # Reuse the report's definitions without printing its front-matter list.
    expected = {'acronyms.tex': MARKER + match[1].replace(r'\acro{', r'\acrodef{')}
    for key, apps in portfolios(root).items():
        expected[f'{key}-index.tex'] = render_index(apps)
        expected[f'{key}-applications.tex'] = render_sections(apps)
    folder = root / 'standalone/portfolios'
    problems = []
    for name, content in expected.items():
        path = folder / name
        if path.exists() and path.read_text() == content:
            continue
        if write:
            if path.exists() and not path.read_text().startswith(MARKER):
                raise ValueError(f'Refusing to overwrite authored content: {path}')
            folder.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        else:
            problems.append(f'Stale: {path.relative_to(root)}')
    for path in folder.glob('*.tex'):
        if path.name not in expected:
            if write:
                if not path.read_text().startswith(MARKER):
                    raise ValueError(f'Refusing to remove authored content: {path}')
                path.unlink()
            else:
                problems.append(f'Orphan: {path.relative_to(root)}')
    return problems


def external_labels(report_aux, local_aux):
    """Import only nonlocal labels; local application links must stay in the fiche."""
    pattern = r'^\\newlabel\{([^}]+)\}'
    local = set(re.findall(pattern, local_aux, re.M))
    return '\n'.join(line for line in report_aux.splitlines()
                     if (match := re.match(pattern, line)) and match[1] not in local) + '\n'


def build_issues(log):
    """Check diagnostics, not the word 'undefined' in harmless package information."""
    issues = [paragraph for paragraph in re.split(r'\n\s*\n', log)
              if 'Warning:' in paragraph
              and re.search(r'undefined|not defined|multiply defined', paragraph)]
    if re.search(r'Missing character:|^!|destination with the same identifier', log, re.M):
        issues.append('LaTeX error, missing character or duplicate PDF destination')
    return issues


def build_companion(root, output):
    """Build a checked report and export the labels required by the fiches."""
    output.mkdir(parents=True, exist_ok=True)
    print('Building the companion report for external references', flush=True)
    run(LATEX_FLAGS + ['exa-ma-deliverables.tex'], root, output / 'report-build.log')
    check_log(root / 'exa-ma-deliverables.log')
    shutil.copy2(root / 'exa-ma-deliverables.pdf', output / 'exa-ma-deliverables.pdf')
    (output / 'report-labels.aux').write_text(read_labels(root / 'exa-ma-deliverables.aux'))


def build(root=ROOT, ids=None, ref='local-uncommitted-review', revision=None, jobs=1,
          companion=None):
    """Build all selected portfolios with a shared, unchanged report as reference target."""
    catalogue = portfolios(root)
    ids = sorted(catalogue) if not ids else ids
    unknown = set(ids) - catalogue.keys()
    if unknown:
        raise ValueError('Unknown/inactive framework: ' + ', '.join(sorted(unknown)))
    output = root / 'output/pdf/frameworks'
    output.mkdir(parents=True, exist_ok=True)
    if companion is None:
        build_companion(root, output)
        companion = output
    else:
        shutil.copy2(companion / 'exa-ma-deliverables.pdf', output / 'exa-ma-deliverables.pdf')
    report_aux = (companion / 'report-labels.aux').read_text()
    info_command = ['python3', 'scripts/framework_previews.py', '--build-info', '--ref', ref]
    if revision:
        info_command += ['--revision', revision]
    subprocess.run(info_command, cwd=root, check=True,
                   stdout=subprocess.DEVNULL)

    def build_one(key):
        print(f'Building {key}: framework + {len(catalogue[key])} application(s)', flush=True)
        job = f'exa-ma-framework-{key}'
        # Compile in the source directory so minted 2 can find its Pygments input.
        command = LATEX_FLAGS + [f'-jobname={job}']
        entry = f'standalone/frameworks/{key}.tex'
        run(command + [entry], root, output / f'{key}-build.log')
        aux = root / f'{job}.aux'
        # First pass identifies every label actually defined by the reused scientific sources.
        reference = output / f'{key}-references.aux'
        filtered = external_labels(report_aux, aux.read_text())
        changed = not reference.exists() or reference.read_text() != filtered
        if changed:
            reference.write_text(filtered)
        relative = reference.relative_to(root).with_suffix('').as_posix()
        # latexmk does not notice a changed -usepretex value by itself. Force
        # the external-label pass after an unresolved first pass or new labels.
        initial_log = (root / f'{job}.log').read_text(errors='replace')
        force = ['-g'] if changed or build_issues(initial_log) else []
        run(command + force + [r'-usepretex=\def\FrameworkReferenceAux{' + relative + '}', entry],
            root, output / f'{key}-build.log')
        log = (root / f'{job}.log').read_text(errors='replace')
        if issues := build_issues(log):
            raise ValueError(f'Invalid PDF diagnostics: {key}; inspect {job}.log\n' + '\n'.join(issues))
        for extension in ('pdf', 'fls', 'log'):
            name = f'{job}.{extension}'
            shutil.copy2(root / name, output / name)
        print(f'Completed {key}', flush=True)

    with ThreadPoolExecutor(max_workers=jobs) as executor:
        # Each TeX job has its own output prefix, bibliography and minted cache.
        list(executor.map(build_one, ids))
    version = tomllib.loads((root / 'pyproject.toml').read_text())['project']['version']
    manifest = {'report_version': version,
                'revision': revision or subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=root, text=True).strip(),
                'ref': ref,
                'working_tree': ('modified' if subprocess.run(['git', 'diff', '--quiet'], cwd=root).returncode
                                 else 'tracked sources clean'),
                'association_sources': ['data/frameworks.csv', 'data/applications.csv',
                                        'data/application-reconciliation-v3.csv',
                                        'data/applications-source.json'],
                'evidence_source': 'data/benchmark-registry-v3.csv',
                'frameworks': {key: {'pdf': f'exa-ma-framework-{key}.pdf',
                                     'applications': [app['id'] for app in catalogue[key]]} for key in ids}}
    pdfs = [output / f'exa-ma-framework-{key}.pdf' for key in ids] + [output / 'exa-ma-deliverables.pdf']
    manifest['sha256'] = {path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in pdfs}
    manifest['source_sha256'] = {str(path.relative_to(root)): hashlib.sha256(path.read_bytes()).hexdigest()
                                 for path in [root / value for value in manifest['association_sources']
                                               + [manifest['evidence_source']]]}
    for key in ids:
        recorder = output / f'exa-ma-framework-{key}.fls'
        for line in recorder.read_text().splitlines():
            if not line.startswith('INPUT '):
                continue
            path = (root / line[6:]).resolve()
            if (path.is_relative_to(root) and not path.is_relative_to(root / 'output')
                    and path.suffix in {'.tex', '.bib', '.sty', '.csv', '.json'} and path.is_file()):
                manifest['source_sha256'][path.relative_to(root).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    manifest_path = output / 'manifest.json'
    manifest_path.write_text(json.dumps(manifest, indent=2) + '\n')
    archive = root / 'output/framework-consolidated-fiches-review.zip'
    with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED) as bundle:
        for path in pdfs + [manifest_path]:
            bundle.write(path, path.name)
    print(f'Review bundle: {archive}', flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument('--build', action='store_true')
    modes.add_argument('--build-companion', type=Path, metavar='DIRECTORY',
                       help='Build the report and labels for reuse by multiple fiche jobs')
    parser.add_argument('--companion-dir', type=Path,
                        help='Reuse the PDF and labels from --build-companion')
    parser.add_argument('--framework', action='append', help='Build only this active framework (repeatable)')
    parser.add_argument('--ref', default='local-uncommitted-review')
    parser.add_argument('--revision')
    parser.add_argument('--jobs', type=int, default=1, help='Concurrent independent TeX builds (default: 1)')
    args = parser.parse_args()
    if args.jobs < 1:
        parser.error('--jobs must be positive')
    problems = sync(write=args.write)
    if problems:
        parser.exit(1, '\n'.join(problems) + '\nRun with --write after catalogue changes.\n')
    if args.build_companion:
        build_companion(ROOT, args.build_companion)
    if args.build:
        build(ids=args.framework, ref=args.ref, revision=args.revision, jobs=args.jobs,
              companion=args.companion_dir)


if __name__ == '__main__':
    main()
