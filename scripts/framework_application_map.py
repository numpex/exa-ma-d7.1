#!/usr/bin/env python3
"""Generate the framework/application/WP navigation table from catalogue snapshots."""
import argparse
import re
from collections import defaultdict
from pathlib import Path

try:
    from .framework_publication import framework_id, publication_flags
    from .sync_applications import read_csv, tex
except ImportError:
    from framework_publication import framework_id, publication_flags
    from sync_applications import read_csv, tex

ROOT = Path(__file__).resolve().parents[1]
TARGET = 'chapters/framework-application-map.tex'
MARKER = '% Generated by scripts/framework_application_map.py; edit the catalogue snapshots.\n'
STAGES = {
    'benchmark-ready': 'Benchmark ready',
    'implementation-in-progress': 'Implementation in progress',
    'benchmark-in-progress': 'Benchmarking in progress',
    'prototype-ready': 'Prototype ready',
    'spec-only': 'Specification',
    'brainstorming': 'Concept',
    '': 'Not supplied',
}


def link(label, title):
    if not re.fullmatch(r'[A-Za-z0-9:+/ ._-]+', label):
        raise ValueError(f'Unsafe cross-reference label: {label}')
    return r'\hyperref[' + label + ']{' + tex(title) + '}'


def wp_links(value):
    return ', '.join(link(f'chap:wp{wp}', f'WP{wp}')
                     for wp in sorted(set(re.findall(r'WP([1-7])', value)))) or '---'


def application_label(root, app, reconciled):
    record = reconciled.get(app['id'])
    if not record:
        raise ValueError(f"Reconcile the application fiche first: {app['id']}")
    relative = Path(record['latex_spec'])
    source = root / relative
    if relative.is_absolute() or '..' in relative.parts:
        raise ValueError(f'Invalid application source: {relative}')
    if relative == Path(f"chapters/applications/specs/{app['id']}.tex") and not source.exists():
        return None
    if not source.is_file():
        raise ValueError(f'Missing application source: {relative}')
    text = source.read_text()
    standard = 'sec:app:specs:' + app['id']
    # VThreeApplicationDraft defines this label, including catalogue aliases.
    if (r'\label{' + standard + '}' in text
            or r'\VThreeApplicationDraft{' + app['id'] + '}' in text):
        return standard
    raise ValueError(f"No application navigation label for {app['id']}: {source}")


def application_entry(root, app, reconciled):
    label = application_label(root, app, reconciled)
    return (link(label, app['name']) if label
            else tex(app['name']) + r' (\emph{fiche pending})')


def render(root=ROOT, *, applications=None, reconciliation=None):
    _, framework_rows = read_csv(root / 'data/frameworks.csv')
    if applications is None:
        _, applications = read_csv(root / 'data/applications.csv')
    if reconciliation is None:
        _, reconciliation = read_csv(root / 'data/application-reconciliation-v3.csv')
    flags = publication_flags(root)
    by_id = {framework_id(row['Name']): row for row in framework_rows}
    names = {row['Name'].strip().casefold(): key for key, row in by_id.items()}
    rec = {row['application_id']: row for row in reconciliation}
    ids = [row['id'] for row in applications]
    if len(set(ids)) != len(ids):
        raise ValueError('Duplicate application IDs')
    # Only actual report entry points receive links to framework sections.
    entries = re.findall(r'\\FrameworkFicheInput\{([^}]+)\}\{([^}]+)\}',
                         (root / 'chapters/software.tex').read_text())
    report = {key: path for key, path in entries if flags[key]}
    groups = {key: defaultdict(list) for key in report}
    unassigned = []
    for app in sorted(applications, key=lambda row: row['id']):
        associated = {names[value.strip().casefold()]
                      for value in app['Framework'].split(',')
                      if value.strip().casefold() in names}
        if not app['Framework'].strip():
            unassigned.append(app)
        for key in associated & report.keys():
            wps = ', '.join('WP' + value for value in sorted(
                set(re.findall(r'WP([1-7])', app['work_package']))))
            groups[key][(wps, app['status'].strip())].append(
                application_entry(root, app, rec))
    rows = []
    for key in sorted(report):
        framework = by_id[key]
        text = (root / report[key]).read_text()
        labels = re.findall(r'\\label\{(sec:[^}]+:software)\}', text)
        if not labels:
            raise ValueError(f'Missing framework section label: {key}')
        title = link(labels[0], framework['Name'])
        first = True
        for (wps, status), apps in sorted(groups[key].items()):
            if not first:
                rows.append(r'\addlinespace[2pt]')
            rows.append(title + ' & ' + r';\newline '.join(apps) + ' & '
                        + wp_links(wps) + ' & ' + tex(STAGES.get(status, status)) + r' \\')
            first = False
        if first:
            wps = ', '.join(f'WP{i}' for i in range(1, 8) if framework[f'WP{i}'].strip())
            rows.append(title + ' & No application association recorded. & '
                        + wp_links(wps) + r' & Framework scope only \\')
        rows.append(r'\midrule')
    if rows:
        rows.pop()  # The table supplies its own closing rule.
    header = r'\textbf{Framework} & \textbf{Application fiches} & \textbf{WP(s)} & \textbf{Catalogue stage} \\'
    output = MARKER + r"""\begingroup
\small
\setlength{\tabcolsep}{3pt}
\renewcommand{\arraystretch}{1.12}
\begin{longtable}{@{}>{\raggedright\arraybackslash}p{0.14\linewidth}
  >{\raggedright\arraybackslash}p{0.44\linewidth}
  >{\raggedright\arraybackslash}p{0.16\linewidth}
  >{\raggedright\arraybackslash}p{\dimexpr0.26\linewidth-6\tabcolsep\relax}@{}}
\caption{Frameworks in this chapter, registered applications and work packages.}
\label{tab:framework-application-map}\\
\toprule
""" + header + '\n' + r"""\midrule
\endfirsthead
\multicolumn{4}{@{}l}{\textit{Frameworks, applications and work packages (continued)}}\\
\toprule
""" + header + '\n' + r"""\midrule
\endhead
\bottomrule
\endfoot
""" + '\n'.join(rows) + '\n' + r"""\end{longtable}
\endgroup
"""
    if unassigned:
        output += ('\\noindent\\textbf{Catalogue associations to complete.} '
                   + '; '.join(application_entry(root, app, rec)
                               + ' (' + wp_links(app['work_package']) + ')' for app in unassigned)
                   + '. Their Framework field is empty; no association is inferred from an application name.\n')
    return output


def sync(root=ROOT, check=False):
    path = root / TARGET
    expected = render(root)
    if path.exists() and not path.read_text().startswith(MARKER):
        raise ValueError(f'Refusing to overwrite authored content: {path}')
    stale = not path.exists() or path.read_text() != expected
    if stale and not check:
        path.write_text(expected)
    return stale


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        stale = sync(check=args.check)
    except ValueError as error:
        parser.error(str(error))
    if stale and args.check:
        parser.exit(1, f'Stale: {TARGET}\n')
    print('Framework/application navigation ' + ('checked' if args.check else 'generated'))


if __name__ == '__main__':
    main()
