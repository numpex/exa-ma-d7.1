#!/usr/bin/env python3
"""Read explicit fiche publication flags; keep inactive catalogue/source data."""
import argparse
import csv
import io
import json
import re
from datetime import date
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
FIELD = 'Include in deliverable'
MARKER = '% Generated by scripts/framework_publication.py; edit data/frameworks.csv.\n'


def framework_id(name):
    key = name.strip().replace('+', 'p').replace(' ', '-').replace('/', '-').replace('_', '-').lower()
    key = {'arcane': 'arcane-framework'}.get(key, key)
    if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', key):
        raise ValueError(f'Unsafe framework name: {name!r}')
    return key


def refresh_sheet(root=ROOT, fetch=None):
    """Refresh only publication flags from the configured Sheet; preserve other cells."""
    source = root / 'data/frameworks-source.json'
    provenance = json.loads(source.read_text())
    match = re.fullmatch(r'https://docs\.google\.com/spreadsheets/d/([A-Za-z0-9_-]+)/.*',
                         provenance['spreadsheet_url'])
    if not match:
        raise ValueError('Expected a Google Sheets URL in frameworks-source.json')
    url = (f'https://docs.google.com/spreadsheets/d/{match[1]}/export?format=csv'
           f'&gid={int(provenance["sheet_id"])}')
    if fetch is None:
        with urlopen(url, timeout=30) as response:
            text = response.read().decode('utf-8-sig')
    else:
        text = fetch(url)
    remote = csv.DictReader(io.StringIO(text))
    if not {'Name', FIELD}.issubset(remote.fieldnames or []):
        raise ValueError(f'Google Sheet is missing Name or {FIELD!r}')
    flags = {}
    for row in remote:
        name = row['Name']
        if not name and not any(row.values()):
            continue
        if not name or name in flags:
            raise ValueError('Google Sheet has an empty or duplicate framework name')
        flag = (row[FIELD] or '').strip().upper()
        if flag not in {'TRUE', 'FALSE'}:
            raise ValueError(f'Google Sheet: {name}: {FIELD} must be TRUE or FALSE')
        flags[name] = flag
    path = root / 'data/frameworks.csv'
    with path.open(newline='', encoding='utf-8-sig') as stream:
        local = csv.DictReader(stream)
        fields, rows = local.fieldnames, list(local)
    if not fields or 'Name' not in fields:
        raise ValueError('Local catalogue is missing Name')
    names = [row['Name'] for row in rows]
    if len(set(names)) != len(names) or set(names) != set(flags):
        raise ValueError('Framework names differ: refresh/reconcile the full catalogue first')
    if FIELD not in fields:
        fields.append(FIELD)
    for row in rows:
        row[FIELD] = flags[row['Name']]
    output = io.StringIO(newline='')
    writer = csv.DictWriter(output, fields, lineterminator='\n', quoting=csv.QUOTE_ALL)
    writer.writeheader()
    writer.writerows(rows)
    entry = provenance.setdefault('entry_refreshes', {}).setdefault('publication_scope', {})
    entry.update(date=date.today().isoformat(), changed_fields=[FIELD],
                 scope='Only publication flags were refreshed from the configured Google Sheet; '
                       'all other snapshot fields were preserved.')
    # All validation precedes writes; no scientific metadata is refreshed here.
    path.write_text(output.getvalue())
    source.write_text(json.dumps(provenance, indent=2, ensure_ascii=False) + '\n')


def publication_flags(root=ROOT):
    path = root / 'data/frameworks.csv'
    with path.open(newline='', encoding='utf-8-sig') as stream:
        reader = csv.DictReader(stream)
        if not {'Name', FIELD}.issubset(reader.fieldnames or []):
            raise ValueError(f'{path}: missing Name or {FIELD!r} column')
        result = {}
        for number, row in enumerate(reader, 2):
            key = framework_id(row['Name'])
            if key in result:
                raise ValueError(f'{path}:{number}: duplicate framework {key}')
            flag = (row[FIELD] or '').strip().upper()
            if flag not in {'TRUE', 'FALSE'}:
                raise ValueError(f'{path}:{number}: {FIELD} must be TRUE or FALSE')
            result[key] = flag == 'TRUE'
    return result


def render(root=ROOT):
    flags = publication_flags(root)
    return MARKER + ''.join(
        r'\expandafter\def\csname ExamaFrameworkIncluded@' + key
        + r'\endcsname{' + str(int(value)) + '}\n'
        for key, value in sorted(flags.items()))


def sync(root=ROOT, write=False):
    path = root / 'software/framework-publication.tex'
    expected = render(root)
    if path.exists() and not path.read_text().startswith(MARKER):
        raise ValueError(f'Refusing to overwrite authored publication data: {path}')
    if path.exists() and path.read_text() == expected:
        return []
    if write:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected)
        return []
    return [f'Stale framework publication data: {path}']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--refresh-sheet', action='store_true',
                        help='Refresh only the publication column from the configured Google Sheet')
    args = parser.parse_args()
    if args.check and args.refresh_sheet:
        parser.error('--check cannot refresh the snapshot')
    try:
        if args.refresh_sheet:
            refresh_sheet()
        problems = sync(write=not args.check)
    except ValueError as error:
        parser.error(str(error))
    if problems:
        parser.exit(1, '\n'.join(problems) + '\n')
    print('Framework publication flags ' + ('checked' if args.check else 'generated'))


if __name__ == '__main__':
    main()
