#!/usr/bin/env python3
"""Refresh application catalogue metadata from a local Applications CSV snapshot.

Never writes scientific fiches. Benchmark evidence and editorial reconciliation
notes are retained. Requested per-application metadata has overwrite protection.
"""
import argparse
import csv
import io
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED = "% Generated by scripts/sync_applications.py; edit the CSV snapshot.\n"
FIELDS = {
    "responsible": "Responsible (Permanent)", "wp_mapping": "work_package",
    "application_type": "application_type", "software_framework": "Framework",
    "status_maturity": "status", "benchmark_scope": "Benchmark scope",
    "metrics": "metrics", "repository_url": "repo_url",
    "specification_url": "tex_url",
}


def read_csv(path):
    with path.open(newline="", encoding="utf-8") as stream:
        reader = csv.DictReader(stream)
        return reader.fieldnames, list(reader)


def csv_text(fields, rows):
    stream = io.StringIO(newline="")
    writer = csv.DictWriter(stream, fieldnames=fields, lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    return stream.getvalue()


def tex(value):
    escapes = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%",
               "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
               "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(escapes.get(c, c) for c in value)


def value_or_missing(value, context=""):
    if value:
        return tex(value)
    label = "[" + tex(context) + "]" if context else ""
    return r"\todo" + label + "{Sheet field missing.}"


def normalized_list(value):
    return "; ".join(part.strip() for part in value.split(",") if part.strip())


def replace_rows(source, rows, prefix, name):
    """Replace only the catalogue's data rows; preserve surrounding prose/style."""
    start_marker, end_marker = f"% BEGIN GENERATED {name}\n", f"% END GENERATED {name}\n"
    if start_marker in source:
        start = source.index(start_marker)
        end = source.index(end_marker, start) + len(end_marker)
    else:
        start = source.index(r"\nolinkurl{" + prefix)
        end = source.index(r"\bottomrule", start)
    return source[:start] + start_marker + "\n".join(rows) + "\n" + end_marker + source[end:]


def metadata(row):
    fields = ["id", "name", "Partners", "PC", "Responsible (Permanent)",
              "WP7 Engineer", "work_package", "application_type", "purpose",
              *[f"Method-Algorithm WP{i}" for i in range(1, 7)], "WP7",
              "inputs", "outputs", "metrics", "status", "Benchmark scope",
              "Framework", "parallel_framework", "repo_url", "tex_url", "notes"]
    pairs = [tex(key) + " & " + value_or_missing(row.get(key, ""), row["id"] + " / " + key) + r" \\" for key in fields
             if (not key.startswith("Method-Algorithm") and key not in {"WP7", "notes"}) or row.get(key)]
    return GENERATED + (
        r"\begin{FicheMetadataTable}" "\n"
        + "\n".join(pairs) + "\n"
        r"\end{FicheMetadataTable}" "\n")


def protected_output(changes, path, content):
    if path.exists() and not path.read_text().startswith(GENERATED):
        raise ValueError(f"Refusing to overwrite unmarked generated file: {path}")
    changes[path] = content


def plan(root, snapshot, metadata_ids, standalone=False):
    _, sheet = read_csv(snapshot)
    required = {"id", "name", *FIELDS.values()}
    if not sheet or not required.issubset(sheet[0]):
        raise ValueError("Snapshot must contain the Applications headers.")
    ids = [r["id"] for r in sheet]
    if len(ids) != len(set(ids)) or any(not re.fullmatch(r"app-[a-z0-9-]+", i) for i in ids):
        raise ValueError("Application IDs must be unique, non-empty and safe filenames.")
    if not set(metadata_ids).issubset(ids):
        raise ValueError("Requested metadata ID is absent from the snapshot.")
    rec_path = root / "data/application-reconciliation-v3.csv"
    rec_fields, old = read_csv(rec_path)
    previous = {r["application_id"]: r for r in old}
    rows = []
    for number, row in enumerate(sheet, 2):
        item = dict(previous.get(row["id"], {key: "" for key in rec_fields}))
        item.update(application_id=row["id"], sheet_row=str(number))
        for target, source in FIELDS.items():
            value = row.get(source, "").strip()
            item[target] = normalized_list(value) if target in {"metrics", "benchmark_scope"} else value
        item["status_maturity"] = item["status_maturity"] or "status-missing"
        if row["id"] not in previous:
            item["latex_spec"] = f"chapters/applications/specs/{row['id']}.tex"
            missing = [f"Sheet {key} missing" for key in ["WP7 Engineer", "inputs", "outputs", "metrics", "repo_url", "tex_url"] if not row.get(key)]
            item["discrepancies"] = "; ".join(missing)
            item["required_action"] = "Owner review of the draft fiche; supply versioned code, validation protocol and evidence"
        if row.get("Responsible (Permanent)"):
            # Remove only obsolete missing-owner observations; retain other notes.
            item["discrepancies"] = "; ".join(note for note in item["discrepancies"].split("; ")
                if not note.startswith("Sheet owner missing") and note not in {
                    "Sheet responsible missing", "Sheet responsible contributor missing",
                    "PR #115 names L. Gouarin but the Sheet responsible field is empty"})
            item["required_action"] = "; ".join(note for note in item["required_action"].split("; ")
                if note != "Owner must resolve responsible-contributor discrepancy")
        rows.append(item)
    rows.extend(row for row in old if row["application_id"] not in ids)

    bench_path = root / "data/benchmark-registry-v3.csv"
    bench_fields, benchmarks = read_csv(bench_path)
    by_app = {r["id"]: r for r in sheet}
    for item in benchmarks:
        if item["application_id"] in by_app:
            row = by_app[item["application_id"]]
            item["responsible"] = row["Responsible (Permanent)"]
            item["contributing_wps"] = row["work_package"]
            if row["Responsible (Permanent)"]:
                item["known_limitations"] = "; ".join(note for note in item["known_limitations"].split("; ")
                    if not note.startswith("Sheet owner missing"))
    # Never invent benchmark IDs, contracts, KPIs or results from application rows.
    # Existing contributor-supplied benchmark records remain separate inputs.
    mappings = {}
    for b in benchmarks:
        mappings.setdefault(b["application_id"], []).append(b["benchmark_id"])
    changes = {rec_path: csv_text(rec_fields, rows), bench_path: csv_text(bench_fields, benchmarks)}
    app_rows, matrix_rows = [], []
    for row in sorted(rows, key=lambda row: row["application_id"]):
        app_id = row["application_id"]
        wp = ", ".join(re.findall(r"WP([1-7])", row["wp_mapping"]))
        bids = "; ".join(r"\nolinkurl{" + bid + "}" for bid in mappings.get(app_id, [])) or "---"
        app_rows.append(r"\nolinkurl{" + app_id + "} & " + (row["sheet_row"] or "---") + " & " + (wp or "---")
            + " & " + value_or_missing(row["software_framework"], app_id + " / Framework") + r" & \nolinkurl{" + row["status_maturity"] + "} & " + bids + r" \\")
        wps = set(re.findall(r"WP([1-7])", row["wp_mapping"]))
        matrix_rows.append(r"\nolinkurl{" + app_id + "} & " + " & ".join("x" if str(i) in wps else "" for i in range(1, 8)) + r" \\")
    for filename, generated_rows, prefix, name in [
        ("chapters/applications/registry.tex", app_rows, "app-", "APPLICATION REGISTRY"),
        ("chapters/applications/cross-wp-matrix.tex", matrix_rows, "app-", "CROSS WP MATRIX"),
        ("chapters/applications/benchmark-index.tex", [r"\nolinkurl{" + b["benchmark_id"] + r"} & \BenchmarkRegistryApplication{" + b["application_id"] + "} & " + tex(b["benchmark_category"]) + " & " + tex(b["benchmark_status"]) + r" \\" for b in sorted(benchmarks, key=lambda b: (b["application_id"], b["benchmark_id"]))], "BM-", "BENCHMARK REGISTRY")]:
        path = root / filename
        changes[path] = replace_rows(path.read_text(), generated_rows, prefix, name)
        if name == "APPLICATION REGISTRY":
            counts = ("% BEGIN GENERATED APPLICATION COUNTS\n"
                + r"\def\ApplicationSheetCount{" + str(len(sheet)) + "}\n"
                + r"\def\ApplicationSheetLastRow{" + str(len(sheet) + 1) + "}\n"
                + "% END GENERATED APPLICATION COUNTS\n")
            source = changes[path]
            if "% BEGIN GENERATED APPLICATION COUNTS\n" in source:
                source = re.sub(r"% BEGIN GENERATED APPLICATION COUNTS\n.*?% END GENERATED APPLICATION COUNTS\n",
                    lambda _: counts, source, flags=re.S)
            else:
                first_line, rest = source.split("\n", 1)
                source = first_line + "\n" + counts + rest
            changes[path] = source
    requested_metadata = set(metadata_ids)
    if standalone:
        # Refresh existing managed metadata used by dedicated local fiches too.
        # Authored files without the marker are never added implicitly.
        for path in (root / "chapters/applications/metadata").glob("*.tex"):
            if path.stem in by_app and path.read_text().startswith(GENERATED):
                requested_metadata.add(path.stem)
        for row in rows:
            app_id = row["application_id"]
            if not re.fullmatch(r"app-[a-z0-9-]+", app_id):
                raise ValueError(f"Unsafe application ID: {app_id}")
            source = Path(row["latex_spec"])
            grouped = source.as_posix() == "chapters/applications/specs/app-proposed.tex"
            if grouped:
                text = (root / source).read_text()
                if f"%<*{app_id}>" not in text or f"%</{app_id}>" not in text:
                    raise ValueError(f"Missing shared-fiche selection markers for {app_id}")
            # A WP scientific chapter is not a dedicated application fiche.
            dedicated = source.parent.as_posix() == "chapters/applications/specs" and not grouped
            basename = source.stem if dedicated else app_id
            if not re.fullmatch(r"app-[a-z0-9-]+", basename):
                raise ValueError(f"Unsafe specification basename: {basename}")
            wrapper = (GENERATED + "% Compile from the repository root.\n"
                + r"\def\ApplicationId{" + app_id + "}\n"
                + r"\def\ApplicationSpec{" + basename + "}\n")
            if grouped:
                wrapper += r"\def\ApplicationGroupedSource{" + source.as_posix() + "}\n"
            elif not (root / f"chapters/applications/specs/{basename}.tex").exists():
                if app_id not in by_app:
                    raise ValueError(f"No fiche or Sheet metadata available for {app_id}")
                requested_metadata.add(app_id)
            wrapper += r"\input{standalone/application}" + "\n"
            protected_output(changes, root / f"standalone/applications/{app_id}.tex", wrapper)
    for app_id in requested_metadata:
        path = root / f"chapters/applications/metadata/{app_id}.tex"
        protected_output(changes, path, metadata(by_app[app_id]))
    return changes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--snapshot", type=Path, default=ROOT / "data/applications.csv")
    parser.add_argument("--metadata", action="append", default=[], metavar="APP_ID")
    parser.add_argument("--standalone", action="store_true", help="Generate a named preview for every catalogue application")
    parser.add_argument("--check", action="store_true", help="Report stale outputs without writing")
    args = parser.parse_args()
    changes = plan(ROOT, args.snapshot, args.metadata, args.standalone)
    stale = [path for path, content in changes.items() if not path.exists() or path.read_text() != content]
    for path in stale:
        print(("Stale: " if args.check else "Updating: ") + str(path.relative_to(ROOT)))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(changes[path])
    if args.check and stale:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
