#!/usr/bin/env python3
"""Generate mesh/app discovery material; authored scientific fiches stay separate.

Local JSON supplies deliverable metadata only. The apps-feelpp repository owns
its case inputs, benchmark configurations and mesh documentation; never export
this snapshot over those application sources.
"""
import argparse
import json
import re
from pathlib import Path
try:
    from .framework_portfolios import portfolios
    from .sync_applications import tex
except ImportError:
    from framework_portfolios import portfolios
    from sync_applications import tex
ROOT = Path(__file__).resolve().parents[1]
TEX_MARKER = '% Generated by scripts/feelpp_catalogue.py; edit data/feelpp-mesh-catalogue.json.\n'
ADOC_MARKER = '// Generated by scripts/feelpp_catalogue.py; edit the D7.1 catalogue.\n'


def validate(data, root=ROOT):
    families = data['families']
    apps = data['applications']
    for records in (families, apps):
        ids = [r['id'] for r in records]
        if len(ids) != len(set(ids)):
            raise ValueError('Duplicate catalogue ID')
        if any(not re.fullmatch('[a-z0-9-]+', x) for x in ids):
            raise ValueError('Unsafe catalogue ID')
    actual = {a['id']: a for a in portfolios(root)['feelpp']}
    if {a['id'] for a in apps} != actual.keys():
        raise ValueError('Feel++ application coverage differs from the catalogue')
    family_ids = {f['id'] for f in families}
    for app in apps:
        if not app['mesh_families'] or not set(app['mesh_families']) <= family_ids:
            raise ValueError('Unknown or empty mesh family: ' + app['id'])
        if app['fiche_source'] != actual[app['id']]['source']:
            raise ValueError('Fiche source mismatch: ' + app['id'])
    for record in apps + families:
        for key in ('existing_paths', 'repository_files'):
            for name in record.get(key, []):
                p = Path(name)
                if p.is_absolute() or '..' in p.parts:
                    raise ValueError('Unsafe repository path: ' + name)
    for family in families:
        # Numbers/hashes need a real dataset record, never inferred from a paper.
        if family['mesh_counts'] is not None or family['mesh_sha256'] is not None:
            raise ValueError('Add a versioned dataset record before publishing mesh statistics')
    return data


def local_outputs(data):
    apps = data['applications']
    families = {f['id']: f for f in data['families']}
    lines = [TEX_MARKER, r'\begin{FicheMetadataTable}[Feel++ applications and work-package connections.]']
    for app in apps:
        lines.append(r'\hyperref[' + app['fiche_label'] + ']{' + tex(app['title']) + '} & '
                     + tex(app['work_packages']) + r'; \nolinkurl{' + app['id'] + r'} \\')
    lines += [r'\end{FicheMetadataTable}', r'\subsection{Shared mesh catalogue}',
              r'\label{sec:Feelpp:meshes}',
              'Mesh families are shared identifiers, not a claim that every input file is already distributed.',
              r'\begin{FicheMetadataTable}[Shared mesh families: availability and remaining dataset work.]']
    for f in families.values():
        lines.append(r'\phantomsection\label{mesh:feelpp:' + f['id'] + '}' + tex(f['title']) + ' & '
                     + tex(f['referenced_levels'] + '. ' + f['availability']) + r' \\')
    lines += [r'\end{FicheMetadataTable}',
              r'\paragraph{Configuration-first application contract.}',
              r'A toolbox case consists of versioned CFG settings, a JSON physical model, mesh references and launch settings. New C++ is required only when the selected numerical kernel needs it.',
              r'Each \nolinkurl{apps/<application-id>/} entry in the application repository links the fiche, existing implementation/configurations, mesh family and planned files. Mesh counts and SHA-256 digests remain unset until the actual files are archived. Record geometry units, boundary/material labels, mesh-generator revision/options, partitions and per-order degrees of freedom for each delivered level.']
    outputs = {Path('software/feelpp/application-catalogue.tex'): '\n'.join(lines) + '\n'}
    for app in apps:
        lines = [TEX_MARKER, r'\subsection{Application package and shared meshes}',
                 r'\begin{FicheMetadataTable}',
                 'Repository entry & ' + r'\nolinkurl{apps/' + app['id'] + r'/} (local review layout in apps-feelpp; publication pending) \\',
                 'Delivery model & ' + tex(app['delivery'].replace('-', ' ')) + r' \\',
                 'Available material & ' + tex(app['present_material']) + r' \\',
                 'Results status & ' + tex(app['results_status']) + r' \\']
        for id in app['mesh_families']:
            f = families[id]
            lines.append(r'\hyperref[mesh:feelpp:' + id + ']{' + tex(f['title']) + '} & '
                         + tex(f['geometry_units'] + ' ' + f['required']) + r' \\')
        lines += [r'\end{FicheMetadataTable}', r'\paragraph{Next contribution.} ' + tex(app['remaining']),
                  ]
        outputs[Path('chapters/applications/meshes') / (app['id'] + '.tex')] = '\n'.join(lines) + '\n'
    review = [ADOC_MARKER, '= Feel++ fiche review and remaining contributions',
              ':toc:', '', 'Review date: ' + data['review_date'] + '.',
              'Configuration availability, scientific specification and measured results are assessed separately. '
              'Toolbox CFG/model JSON files count as implementation; new C++ and new results are not required for every fiche.',
              '', '[cols="2,1,3,4",options="header"]', '|===', '|Framework / application |Priority |Fiche assessment / current material |Remaining action',
              '|Feel++ framework |Normal |C++23, coupling, 14 application links and shared mesh catalogue. '
              '|Confirm public links after publishing the local application layout; review dataset completeness with owners.']
    for app in apps:
        review += ['|' + app['title'] + ' +\n`' + app['id'] + '`', '|' + app['priority'],
                   '|' + app['fiche_review'] + ' +\n' + app['present_material'], '|' + app['remaining']]
    review += ['|===', '', '== Shared dataset acceptance checklist',
               'For each mesh level, retain the generator or immutable download, license/access conditions, units, physical markers, cell/node/DoF counts, SHA-256 digest and partition recipe. '
               'Published reference counts do not establish availability of those meshes.',
               'No new campaign is required to accept the scientific description. Planned items must retain their status until the corresponding files or run records exist.', '', '== Checks after revision', 'All 14 source fiches have been re-read against the application inventory. FDA readiness and untraceable mesh counts were corrected; NLCRB now follows the implemented Galerkin/regression method; the forward, inverse and control scopes are separated. The PDF pages and internal/report links were checked after regeneration. Case-owner decisions below remain open; absence of new code or results alone is not a scientific-fiche blocker.']
    outputs[Path('reviews/feelpp-fiche-todo.adoc')] = '\n'.join(review) + '\n'
    return outputs


def sync(outputs, target, write=False):
    stale = []
    for rel, expected in outputs.items():
        path = target / rel
        if path.exists() and path.read_text() == expected:
            continue
        if not write:
            stale.append(str(rel))
            continue
        if path.exists():
            marker = TEX_MARKER if path.suffix == '.tex' else ADOC_MARKER
            if path.suffix != '.json' and not path.read_text().startswith(marker):
                raise ValueError('Refusing to overwrite authored file: ' + str(path))
            if path.suffix == '.json' and json.loads(path.read_text()).get('source_repository') != 'https://github.com/numpex/exa-ma-d7.1':
                raise ValueError('Refusing to overwrite unrelated catalogue: ' + str(path))
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected)
    return stale


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--export-repo', type=Path, help=argparse.SUPPRESS)
    args = parser.parse_args()
    if args.export_repo:
        parser.error('apps-feelpp owns its application layout; --export-repo is retired. Regenerate deliverable metadata locally only.')
    data = validate(json.loads((ROOT/'data/feelpp-mesh-catalogue.json').read_text()))
    stale = sync(local_outputs(data), ROOT, args.write)
    if stale:
        raise SystemExit('Stale generated files: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
