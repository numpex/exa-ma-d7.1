#!/usr/bin/env python3
"""Generate selected framework metadata, never authored fiches or results."""
import argparse
import csv
import re
from pathlib import Path

from jinja2 import Environment, FileSystemLoader, StrictUndefined

ROOT = Path(__file__).resolve().parents[1]
GENERATED = "% Generated by scripts/sync_frameworks.py --framework; edit data/frameworks.csv.\n"
LEGACY_GENERATED = "% Generated by gen.py --framework; edit data/frameworks.csv.\n"


def tex(value):
    escapes = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%",
               "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
               "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(escapes.get(c, c) for c in value)


def items(value):
    # Preserve source order, but avoid duplicate display entries (e.g. VTK).
    # Quoted topics such as "ROM: RB, POD, ..." are a single catalogue item.
    parts = next(csv.reader([value.replace("\n", " ")], skipinitialspace=True))
    return list(dict.fromkeys(p.strip() for p in parts if p.strip()))


def display(value):
    return "; ".join(tex(p.replace("asssociated", "associated")) for p in items(value))


def slug(name):
    return name.replace("+", "p").replace(" ", "-").replace("/", "-").lower()


def link(url, label=None):
    if not re.fullmatch(r"https?://[^\s{}\\%]+", url):
        raise ValueError(f"Unsafe or invalid catalogue URL: {url!r}")
    return r"\href{" + url + "}{" + tex(label or url) + "}"


def plan(root, snapshot, framework):
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", framework):
        raise ValueError("Framework ID must be a safe lowercase filename.")
    with snapshot.open(newline="", encoding="utf-8-sig") as stream:
        reader = csv.DictReader(stream)
        required = {"Name", "Languages", "Interfaces", "Description", "Repository",
                    "Docs", "Benchmarked", "Metadata", "Bottlenecks", "DevOps",
                    "Consortium", "Partner", "Emails", "License", "Parallelism",
                    "Data", "Resilience", "Channels", "API", *[f"WP{i}" for i in range(1, 8)]}
        if not required.issubset(reader.fieldnames or []):
            raise ValueError("Snapshot must contain the Frameworks headers.")
        rows = [r for r in reader if slug(r["Name"]) == framework]
    if len(rows) != 1:
        raise ValueError(f"Expected one entry for {framework}, found {len(rows)}.")
    row = rows[0]
    devops = items(row["DevOps"])

    def category(prefix):
        return display(",".join(p.removeprefix(prefix) for p in devops if p.startswith(prefix)))

    identity = [
        ("Consortium", display(row["Consortium"])),
        ("Exa-MA partners", display(row["Partner"])),
        ("Contacts", display(row["Emails"])),
        ("Benchmark coverage", display(row["Benchmarked"]) + r" (catalogue classification)"),
        ("License", display(row["License"])),
        ("Repository", link(row["Repository"], row["Repository"].removeprefix("https://"))),
        ("Documentation", link(row["Docs"], row["Docs"].removeprefix("https://"))),
        ("Software metadata", display(row["Metadata"])),
    ]
    environment = [
        ("Languages", display(row["Languages"])),
        ("Parallelism", display(row["Parallelism"])),
        ("Data formats/services", display(row["Data"])),
        ("Resilience", display(row["Resilience"])),
        ("CI/CD", display(",".join(p for p in devops if p.startswith("Continuous")))),
        ("Testing", category("Test - ")),
        ("Packages", category("Packages - ")),
        ("Containers", category("Container - ")),
        ("Interfaces", display(row["Interfaces"])),
        ("API practices", display(row["API"])),
    ]
    work_packages = [(f"WP{i}", display(row[f"WP{i}"])) for i in range(1, 8) if row[f"WP{i}"]]
    env = Environment(loader=FileSystemLoader(root / "templates"),
                      undefined=StrictUndefined, keep_trailing_newline=True,
                      block_start_string=r"\BLOCK{", block_end_string="}",
                      variable_start_string=r"\VAR{", variable_end_string="}")
    content = GENERATED + env.get_template("feelpp-metadata.tex.j2").render(
        description=tex(row["Description"]), identity=identity,
        environment=environment, work_packages=work_packages,
        bottlenecks=display(row["Bottlenecks"]))
    target = root / "software" / framework / "metadata.tex"
    if target.exists() and not target.read_text(encoding="utf-8").startswith((GENERATED, LEGACY_GENERATED)):
        raise ValueError(f"Refusing to overwrite unmarked file: {target}")
    return {target: content}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--framework", required=True)
    parser.add_argument("--snapshot", type=Path, default=ROOT / "data/frameworks.csv")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    changes = plan(ROOT, args.snapshot, args.framework)
    stale = []
    for path, content in changes.items():
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if args.check and stale:
        parser.exit(1, "Stale framework metadata: " + ", ".join(str(p) for p in stale) + "\n")
    print(f"{args.framework}: metadata {'checked' if args.check else 'generated'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
