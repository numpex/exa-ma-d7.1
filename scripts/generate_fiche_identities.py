#!/usr/bin/env python3
"""Generate standalone-only identity data; never edit scientific fiche sources."""
import argparse
import csv
import json
import re
from datetime import date
from pathlib import Path
try:
    from .release import current_version
except ImportError:
    from release import current_version

ROOT = Path(__file__).resolve().parents[1]
MARKER = "% Generated by scripts/generate_fiche_identities.py; edit the catalogue/profile inputs.\n"


def tex(value):
    escapes = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%",
               "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
               "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(escapes.get(c, c) for c in value)


def cell(value):
    return tex(" ".join(value.split())) if value.strip() else "Not recorded"


def read_csv(path):
    with path.open(newline="", encoding="utf-8-sig") as stream:
        return list(csv.DictReader(stream))


def link(url, label):
    # Some catalogue repository fields are access notes rather than URLs.
    if not re.fullmatch(r"https?://[^\s{}\\]+", url):
        return ""
    escaped = url.replace("%", r"\%").replace("#", r"\#")
    return r"\href{" + escaped + "}{" + tex(label) + "}"


def declaration(key, kind, title, subtitle, summary, rows, links, source):
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", key):
        raise ValueError(f"Unsafe fiche ID: {key}")
    body = "\n".join(r"\textbf{" + tex(label) + "} & " + value + r" \\" for label, value in rows)
    values = [key, tex(kind), cell(title), tex(subtitle), tex(summary), body,
              r"\enspace\textbar\enspace ".join(filter(None, links)), tex(source)]
    return r"\DeclareFicheIdentity" + "".join("{"+v+"}" for v in values) + "\n"


def render(root):
    version = current_version(root)
    profiles = json.loads((root / "data/fiche-identity-profiles.json").read_text())
    source = json.loads((root / "data/frameworks-source.json").read_text())
    snapshot_date = date.fromisoformat(source["retrieved_on"]).strftime("%d %B %Y").lstrip("0")
    content = MARKER + r"\def\FicheDeliverableVersion{v" + tex(version) + "}\n"
    used = set()
    frameworks = {r["Name"].replace("+", "p").replace(" ", "-").replace("/", "-").lower(): r
                  for r in read_csv(root / "data/frameworks.csv")}
    framework_profiles = profiles.get("frameworks", {})
    framework_ids = set(framework_profiles) | {p.stem for p in (root / "standalone/frameworks").glob("*.tex")}
    aliases = {"arcane-framework": "arcane"}
    for key in sorted(framework_ids):
        profile = framework_profiles.get(key, {})
        row = frameworks[aliases.get(key, key)]
        wps = ", ".join(f"WP{i}" for i in range(1, 8) if row.get(f"WP{i}", "").strip())
        content += declaration(
            key, "Software fiche", row["Name"], profile.get("subtitle", ""),
            profile.get("summary", ""),
            [("Partners", cell(row["Partner"])),
             ("Contacts", cell(row["Emails"])),
             ("Work packages", cell(wps)),
             ("Benchmarks", cell(row["Benchmarked"]))],
            [link(row["Repository"], "Repository"), link(row["Docs"], "Documentation"),
             link(profile.get("doi", ""), "Software DOI")],
            "Framework catalogue refreshed " + snapshot_date)
        used.add(key)
    applications = read_csv(root / "data/applications.csv")
    sheet_ids = {row["id"] for row in applications}
    # Keep repository-only fiches recorded by the reconciliation catalogue.
    # A reviewed display profile can supply a short title from the authored fiche.
    for local in read_csv(root / "data/application-reconciliation-v3.csv"):
        key = local["application_id"]
        if key in sheet_ids:
            continue
        profile = profiles.get("applications", {}).get(key, {})
        if profile and not (root / profile["source"]).is_file():
            raise ValueError(f"Missing identity profile source for {key}")
        applications.append({
            "id": key, "name": profile.get("name", key),
            "purpose": profile.get("purpose", ""),
            "Partners": profile.get("Partners", ""),
            "Responsible (Permanent)": local["responsible"],
            "Framework": local["software_framework"],
            "work_package": local["wp_mapping"],
            "application_type": local["application_type"],
            "status": local["status_maturity"], "repo_url": local["repository_url"],
            "tex_url": local["specification_url"]})
    for row in applications:
        key = row["id"]
        if key in used:
            raise ValueError(f"Duplicate fiche ID: {key}")
        used.add(key)
        content += declaration(
            key, "Application fiche", row["name"], key, row.get("purpose", ""),
            [("Responsible", cell(row.get("Responsible (Permanent)", ""))),
             ("Partners", cell(row.get("Partners", ""))),
             ("Frameworks", cell(row.get("Framework", ""))),
             ("Scope / status", cell(row.get("work_package", "")) + "; "
              + cell(row.get("application_type", "")) + "; " + cell(row.get("status", "")))],
            [link(row.get("repo_url", ""), "Repository"),
             link(row.get("tex_url", ""), "Specification")],
            "Source: local Applications catalogue" if key in sheet_ids
            else "Source: repository fiche and reconciliation catalogue")
    return content


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    target = ROOT / "standalone/identity-data.tex"
    if target.exists() and not target.read_text().startswith(MARKER):
        parser.error(f"Refusing to overwrite unmarked file: {target}")
    content = render(ROOT)
    stale = not target.exists() or target.read_text() != content
    if args.check and stale:
        parser.exit(1, "Stale standalone identity data\n")
    if stale:
        target.write_text(content)
    print("Standalone identity data " + ("checked" if args.check else "generated"))


if __name__ == "__main__":
    main()
