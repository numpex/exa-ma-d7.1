#!/usr/bin/env python3
"""Maintain thin framework wrappers and select review builds; never edit fiches."""
import argparse
import json
import re
import subprocess
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ALIASES = {'maphyspp': 'composyx'}
# Outside the scope of this deliverable; historical sources remain untouched.
EXCLUDED = {'pbb', 'arcane-framework', 'mahyco'}
MARKER = '% Generated by scripts/framework_previews.py; scientific text stays in software/.\n'


def frameworks(root=ROOT):
    return {p.parent.name: p.relative_to(root).as_posix()
            for p in sorted((root / 'software').glob('*/*.tex'))
            if p.stem == p.parent.name and p.parent.name not in ALIASES and p.parent.name not in EXCLUDED}


def wrapper(slug):
    return (MARKER + '% Compile from the repository root.\n'
            + rf'\def\FrameworkId{{{slug}}}' + '\n'
            + rf'\def\FrameworkSource{{software/{slug}/{slug}.tex}}' + '\n'
            + r'\input{standalone/framework}' + '\n')


def selected(changed, catalogue):
    """None means all (release/manual); shared dependencies also rebuild all."""
    if changed is None:
        return sorted(catalogue)
    result = set()
    for name in changed:
        parts = Path(name).parts
        if len(parts) >= 2 and parts[0] == 'software':
            slug = ALIASES.get(parts[1], parts[1])
            if slug in catalogue:
                result.add(slug)
        elif name.startswith('standalone/frameworks/'):
            slug = Path(name).stem
            if slug in catalogue:
                result.add(slug)
        elif name == 'standalone-funtides.tex':
            result.add('funtides')
        elif (name.startswith(('graphics/', 'standalone/framework',
                                'templates/framework-', '.github/workflows/'))
              or name in {'defs.tex', 'references.bib', 'pyproject.toml', 'gen.py',
                          'scripts/framework_previews.py', 'tests/test_gen.py',
                          'tests/test_framework_previews.py'}
              or name.endswith('.sty')):
            # Shared dependencies rebuild all; unrelated chapter edits do not.
            return sorted(catalogue)
    return sorted(result & catalogue.keys())


def sync(root, catalogue, write=False):
    problems = []
    for slug in catalogue:
        path = root / 'standalone/frameworks' / f'{slug}.tex'
        expected = wrapper(slug)
        if path.exists() and path.read_text() == expected:
            continue
        if write:
            if path.exists() and not path.read_text().startswith(MARKER):
                raise ValueError(f'Refusing to overwrite authored file: {path}')
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
        else:
            problems.append(str(path.relative_to(root)))
    for path in (root / 'standalone/frameworks').glob('*.tex'):
        if path.stem not in catalogue:
            problems.append(f'Orphan wrapper: {path.relative_to(root)}')
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--changed-json', type=Path,
                        help='JSON list of changed paths; omit to select all')
    parser.add_argument('--build-info', action='store_true')
    parser.add_argument('--ref', default='local-preview')
    parser.add_argument('--revision')
    args = parser.parse_args()
    catalogue = frameworks()
    problems = sync(ROOT, catalogue, args.write)
    if problems:
        parser.exit(1, '\n'.join(problems) + '\n')
    if args.build_info:
        revision = args.revision or subprocess.check_output(
            ['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
        if not re.fullmatch('[0-9a-f]{40,64}', revision):
            parser.error('Expected a full hexadecimal Git revision')
        ref = re.sub(r'[^A-Za-z0-9._-]', '-', args.ref)
        output = ROOT / 'output/frameworks'
        output.mkdir(parents=True, exist_ok=True)
        version = tomllib.loads((ROOT / 'pyproject.toml').read_text())['project']['version']
        if not re.fullmatch(r'[A-Za-z0-9.+-]+', version):
            parser.error('Invalid project version')
        (output / 'build-info.tex').write_text(
            rf'\renewcommand{{\FrameworkReportVersion}}{{v{version}}}' + '\n'
            + rf'\renewcommand{{\FrameworkBuildRef}}{{{ref}}}' + '\n'
            + rf'\renewcommand{{\FrameworkBuildRevision}}{{{revision[:12]}}}' + '\n')
        (output / 'manifest.json').write_text(json.dumps({
            'report_version': version, 'ref': args.ref, 'revision': revision,
            'frameworks': catalogue, 'former_names': ALIASES, 'excluded': sorted(EXCLUDED)}, indent=2) + '\n')
    changed = json.loads(args.changed_json.read_text()) if args.changed_json else None
    selection = selected(changed, catalogue)
    print(json.dumps({'include': [{'id': slug, 'source': catalogue[slug],
                                  'root': f'standalone/frameworks/{slug}.tex'}
                                 for slug in selection]}))


if __name__ == '__main__':
    main()
